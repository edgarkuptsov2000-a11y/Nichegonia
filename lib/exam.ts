/* =========================================================
   Расчёт результата
========================================================= */

export function calculateScore(answers: ExamAnswer[]): number {
  const regularAnswers = answers.filter(
    (answer) =>
      answer.type !== "secret" &&
      answer.type !== "ultra-secret"
  );

  if (regularAnswers.length === 0) {
    return 0;
  }

  const maxPoints = regularAnswers.reduce(
    (sum, answer) => sum + answer.points,
    0
  );

  const earnedPoints = regularAnswers.reduce(
    (sum, answer) =>
      sum + (answer.isCorrect ? answer.points : 0),
    0
  );

  if (maxPoints === 0) {
    return 0;
  }

  let score = Math.round(
    (earnedPoints / maxPoints) * 100
  );

  /*
   * Секретные вопросы дают небольшой бонус,
   * но не могут сами по себе сломать основной результат.
   */

  const secretBonus = answers
    .filter(
      (answer) =>
        answer.type === "secret" ||
        answer.type === "ultra-secret"
    )
    .reduce((sum, answer) => {
      if (!answer.isCorrect) return sum;

      return (
        sum +
        (answer.type === "ultra-secret" ? 4 : 2)
      );
    }, 0);

  score += secretBonus;

  return Math.min(100, score);
}

